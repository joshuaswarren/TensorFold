//! Source of the expected values: TensorFold v1.1.7's CUDA path. The subtract is zig/kernels/cuda/sample_penalties.cuh:4-10
//! (`*x = __float2bfloat16(__bfloat162float(*x) - SUB[i])`, one fp32 subtract, one round-to-nearest-even), it runs before the
//! draw (zig/src/families/qwen3_5/cuda_engine.zig:517), and a greedy tie goes to the lowest id (zig/kernels/cuda/qwen35_argmax.cuh:1,
//! argmax_take at :4-9). The words below are hand-derived from that arithmetic, not recorded CUDA output.
//! The subnormal row is a recorded device limit: the Apple GPUs we ran (M1 and M2 Max, Honeykrisp) flush fp32 denormals to zero, so a
//! penalty amount below 1.2e-38 changes nothing and this row fails there.
//! Penalties fixture: the CUDA tf_penalize_rows formula's expected BF16
//! words as FIXED literals, derived by hand from the independent CUDA
//! arithmetic (exact bf16 widening, one fp32 subtract, one bf16 RNE) — never
//! generated by the engine's or probe's host helpers. Rows are poisoned
//! bf16 shells (256-byte-aligned data window, 16 tail words of 0xffff) so a
//! GPU run must leave guards and untouched words bit-identical. The
//! subnormal row pins the strict CUDA edge (smallest bf16 normal minus a
//! fp32-only subnormal): a device that flushes fp32 denormals fails this
//! gate honestly instead of the expectation being fitted to it.
const std = @import("std");

/// One 4096-wide penalize workgroup covers the row; even count (bf16 view
/// word padding).
pub const count: usize = 16;
/// Data window offset in elements: 128 bf16 = 256 bytes, the largest
/// minStorageBufferOffsetAlignment Vulkan allows (stages 2-5 use the same).
pub const at: usize = 128;
pub const tail: usize = 16;
pub const poison16: u16 = 0xffff;

pub const Entry = struct { tok: u32, sub: f32 };
pub const Want = struct { tok: u32, word: u16 };

/// What the caller must observe after the penalize dispatch: a greedy
/// winner (run the production draw), or a NonFinite refusal (the greedy
/// finite guard must still reject the row).
pub const Outcome = union(enum) {
    winner: u32,
    non_finite,
};

pub const Row = struct {
    name: []const u8,
    /// The data window's planted words, token index -> bf16 bits.
    planted: []const Want,
    entries: []const Entry,
    wants: []const Want,
    outcome: Outcome,

    /// The whole poisoned shell: guards, data window (planted over 0x0000),
    /// poison tail.
    pub fn shell(r: Row, a: std.mem.Allocator) ![]u16 {
        const bits = try a.alloc(u16, at + count + tail);
        @memset(bits, 0);
        for (bits[at + count ..]) |*b| b.* = poison16;
        for (r.planted) |p| bits[at + p.tok] = p.word;
        return bits;
    }
};

// The RNE words, by hand from the CUDA formula:
//   1.0 (0x3f80) - (-1/256): fp32 1.00390625 = 0x3f808000, exact tie, even
//     half stays -> 0x3f80.
//   1.0 (0x3f80) - (-3/256): fp32 1.01171875 = 0x3f818000, exact tie over an
//     odd lsb rounds away -> 0x3f82.
//   -1.0 (0xbf80) - (1/256): fp32 -1.00390625 = 0xbf808000, tie to even
//     -> 0xbf80.
//   -1.0 (0xbf80) - (3/256): fp32 -1.01171875 = 0xbf818000, magnitude up
//     -> 0xbf82.
pub const rne = Row{
    .name = "rne-ties",
    .planted = &.{
        .{ .tok = 0, .word = 0x3f80 },
        .{ .tok = 1, .word = 0x3f80 },
        .{ .tok = 2, .word = 0xbf80 },
        .{ .tok = 3, .word = 0xbf80 },
    },
    .entries = &.{
        .{ .tok = 0, .sub = -0.00390625 },
        .{ .tok = 1, .sub = -0.01171875 },
        .{ .tok = 2, .sub = 0.00390625 },
        .{ .tok = 3, .sub = 0.01171875 },
    },
    .wants = &.{
        .{ .tok = 0, .word = 0x3f80 },
        .{ .tok = 1, .word = 0x3f82 },
        .{ .tok = 2, .word = 0xbf80 },
        .{ .tok = 3, .word = 0xbf82 },
    },
    .outcome = .{ .winner = 1 }, // token 1 rounds away to 0x3f82 (1.015625), above token 0's 1.0: the largest, no tie
};

// Strict CUDA subnormal/cancellation edge: smallest bf16 normal 2^-126
// (0x0080) minus fp32 2^-133 is 127 * 2^-133, exact in fp32 only as a
// SUBNORMAL — bf16 RNE then lands on 0x007f. A device whose fp32 math
// flushes denormals computes 0x0080 and this gate FAILS, honestly: CUDA
// semantics were not met, and the expectation is not fitted to the flush.
pub const subnormal = Row{
    .name = "subnormal-cancel",
    .planted = &.{.{ .tok = 5, .word = 0x0080 }},
    .entries = &.{.{ .tok = 5, .sub = std.math.pow(f32, 2, -133) }},
    .wants = &.{.{ .tok = 5, .word = 0x007f }},
    .outcome = .{ .winner = 5 },
};

// Adjacent tokens 0 and 1 at 4.0 each, presence 1 / frequency 0.5, count 2
// per token: both lose exactly 2.0 (4.0 - 2.0 = 2.0, exact) and untouched
// token 2 at 3.0 becomes the greedy winner — the winner changed because of
// the penalties, read back from the GPU's own draw.
pub const winner = Row{
    .name = "adjacent-winner",
    .planted = &.{
        .{ .tok = 0, .word = 0x4080 },
        .{ .tok = 1, .word = 0x4080 },
        .{ .tok = 2, .word = 0x4040 },
    },
    .entries = &.{
        .{ .tok = 0, .sub = 2.0 },
        .{ .tok = 1, .sub = 2.0 },
    },
    .wants = &.{
        .{ .tok = 0, .word = 0x4000 },
        .{ .tok = 1, .word = 0x4000 },
        .{ .tok = 2, .word = 0x4040 },
    },
    .outcome = .{ .winner = 2 },
};

// The greedy finite guard survives penalties: a planted NaN the penalties
// never touch refuses the draw, while the penalized word is exact — 1.0
// minus 1.0 is POSITIVE zero (0x0000, never 0x8000).
pub const finite = Row{
    .name = "finite-guard-signed-zero",
    .planted = &.{
        .{ .tok = 4, .word = 0x3f80 },
        .{ .tok = 15, .word = 0x7fc0 },
    },
    .entries = &.{.{ .tok = 4, .sub = 1.0 }},
    .wants = &.{.{ .tok = 4, .word = 0x0000 }},
    .outcome = .non_finite,
};

// Equal after rounding: token 1 (1.0078125, 0x3f81) loses exactly 1/128 and
// lands on 1.0 (0x3f80), bit-equal to token 0. The greedy rule is exact ties
// to the lowest index (the CUDA rule), so token 0 wins; without the penalty
// token 1 would have won.
pub const tie = Row{
    .name = "tie-lowest-index",
    .planted = &.{
        .{ .tok = 0, .word = 0x3f80 },
        .{ .tok = 1, .word = 0x3f81 },
    },
    .entries = &.{.{ .tok = 1, .sub = 0.0078125 }},
    .wants = &.{.{ .tok = 1, .word = 0x3f80 }},
    .outcome = .{ .winner = 0 },
};

pub const rows = [_]Row{ rne, subnormal, winner, finite, tie };

test "every row stages unique tokens inside the window and wants each planted token once" {
    for (&rows) |r| {
        for (r.entries) |e| try std.testing.expect(e.tok < count);
        for (r.planted) |p| try std.testing.expect(p.tok < count);
        for (r.wants) |w| try std.testing.expect(w.tok < count);
        for (r.entries, 0..) |e, i| for (r.entries[i + 1 ..]) |o| {
            try std.testing.expect(e.tok != o.tok); // unique token per entry: no halfword races
        };
        for (r.wants) |w| {
            var planted = false;
            for (r.planted) |p| planted = planted or p.tok == w.tok;
            try std.testing.expect(planted); // every expectation names a word the GPU actually changed
        }
    }
}
